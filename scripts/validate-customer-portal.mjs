import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const read = (path) => readFile(new URL(path, import.meta.url), "utf8");
const portal = await read("../portal.html");
const webhook = await read("../supabase/functions/stripe-webhook/index.ts");
const checkout = await read("../supabase/functions/create-checkout-session/index.ts");
const billing = await read("../supabase/functions/create-billing-portal-session/index.ts");
const onboarding = await read("../supabase/functions/complete-onboarding/index.ts");
const inventario = await read("../supabase/functions/inventario-api/index.ts");
const scripts = [];
let cursor = 0;
while ((cursor = portal.indexOf("<script>", cursor)) !== -1) {
  const start = cursor + "<script>".length;
  const end = portal.indexOf("</script>", start);
  if (end === -1) throw new Error("Unclosed inline script tag");
  scripts.push(portal.slice(start, end));
  cursor = end + "</script>".length;
}
assert.ok(scripts.length > 0, "portal must contain its application script");
for (const script of scripts) new Function(script);
assert.ok(portal.includes("Family Plan — $29/month"));
assert.ok(portal.includes("Full Setup — $99 setup + $49/month"));
assert.ok(portal.includes('value="family"'));
assert.ok(portal.includes('value="full_setup"'));
assert.ok(portal.includes("async function restoreSession()"), "confirmed-email sessions must resume pending onboarding");
assert.ok(portal.includes("await ensureOnboarding(user)"), "session restoration must complete pending household setup");
assert.ok((portal.match(/if\(updateError\)throw updateError;/g)||[]).length >= 3, "onboarding metadata update failures must not be ignored");
assert.ok(portal.includes("sb_publishable_"));
for (const forbidden of ["service_role", "sk_live_", "sk_test_", "whsec_"]) assert.ok(!portal.toLowerCase().includes(forbidden.toLowerCase()));
for (const source of [checkout, billing]) {
  assert.ok(source.includes("auth.getUser"));
  assert.ok(source.includes('.eq("user_id", user.id)'));
  assert.ok(source.includes('.eq("role", "owner")'));
  assert.ok(source.includes("Bearer "));
}
assert.ok(checkout.includes("STRIPE_FAMILY_MONTHLY_PRICE_ID"));
assert.ok(checkout.includes("STRIPE_FULL_SETUP_MONTHLY_PRICE_ID"));
assert.ok(checkout.includes("STRIPE_FULL_SETUP_FEE_PRICE_ID"));
assert.ok(checkout.includes("subscription_data[metadata][household_id]"));
assert.ok(checkout.includes("if (subscriptionError)"), "checkout must fail closed on subscription lookup errors");
assert.ok(billing.includes("Billing service is not configured"), "billing portal must validate required secrets");
assert.ok(billing.includes("if (memberError)"), "billing portal must handle membership lookup errors");
assert.ok(billing.includes("if (subscriptionError)"), "billing portal must handle subscription lookup errors");
assert.ok(onboarding.includes("ctx.userClaims?.id"));
assert.ok(onboarding.includes("complete_customer_onboarding"));
assert.ok(!onboarding.includes("payload.user_id"));
assert.ok(webhook.includes("verifyStripeSignature(rawBody, signature, stripeSecret)"));
assert.ok(webhook.includes("stripe_webhook_events"));
assert.ok(webhook.includes("processed_at"));
assert.ok(webhook.includes('event.type.startsWith("customer.subscription.")'));
assert.ok(!webhook.includes("invoice.payment_succeeded"));
assert.ok(!webhook.includes("invoice.payment_failed"));

assert.ok(inventario.includes("auth.getUser"), "Inventario API must validate the user session");
assert.ok(inventario.includes('.eq("household_id", householdId).eq("user_id", user.id)'), "Inventario API must verify household membership");
assert.ok(inventario.includes('.eq("app_key", "inventario")'), "Inventario API must verify app entitlement");
assert.ok(inventario.includes('["active", "trialing"].includes(subscription.status)'), "Inventario API must require an active subscription");
assert.ok(inventario.includes('admin.rpc("list_customer_medicines"'), "Inventario reads must use the private server-only RPC");
assert.ok(inventario.includes('admin.rpc("create_customer_medicine"'), "Medicine creation must use the server-only RPC");
assert.ok(inventario.includes('admin.rpc("record_customer_dispensing"'), "Dispensing must use the atomic server-only RPC");
assert.ok(!inventario.includes('.schema("customer_data")'), "Private schema must not be exposed through PostgREST");
console.log("Customer portal checks passed.");
